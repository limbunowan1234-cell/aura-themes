"""Render original icon packs for each theme.

Glyphs come from Ionicons (MIT licence, bundled with @expo/vector-icons).
No third-party app logos or trademarks are used: icons are generic functions
(Phone, Mail, Camera...) that the user can assign to any app.
Outputs assets/icons/<theme>/<slot>.png (512x512) and src/data/icons.generated.ts
"""
import json
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VI = os.path.join(ROOT, "node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons")
FONT = os.path.join(VI, "Fonts/Ionicons.ttf")
GLYPHS = json.load(open(os.path.join(VI, "glyphmaps/Ionicons.json")))
THEMES = json.load(open(os.path.join(ROOT, "src/data/themes.json")))
S = 512

SLOTS = [
    ("phone", "Phone", "call"), ("messages", "Messages", "chatbubble"), ("camera", "Camera", "camera"),
    ("photos", "Photos", "images"), ("music", "Music", "musical-notes"), ("settings", "Settings", "settings"),
    ("calendar", "Calendar", "calendar"), ("mail", "Mail", "mail"), ("maps", "Maps", "map"),
    ("browser", "Browser", "compass"), ("clock", "Clock", "time"), ("notes", "Notes", "document-text"),
    ("weather", "Weather", "cloud"), ("video", "Video", "videocam"), ("wallet", "Wallet", "wallet"),
    ("games", "Games", "game-controller"),
]


def hx(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def render_icon(theme, glyph_name):
    st = theme["icon"]
    a, b = np.array(hx(st["bg"][0]), np.float32), np.array(hx(st["bg"][1]), np.float32)
    yy, xx = np.mgrid[0:S, 0:S].astype(np.float32)
    t = np.clip((xx * 0.35 + yy) / (S * 1.35), 0, 1)[..., None]
    bg = a * (1 - t) + b * t
    # soft top highlight
    hl = np.exp(-((yy / S - 0.0) / 0.45) ** 2)[..., None] * 18
    img = Image.fromarray(np.clip(bg + hl, 0, 255).astype(np.uint8), "RGB")
    name = glyph_name + ("-outline" if st.get("outline") and (glyph_name + "-outline") in GLYPHS else "")
    ch = chr(GLYPHS[name])
    font = ImageFont.truetype(FONT, int(S * 0.5))
    d = ImageDraw.Draw(img)
    box = d.textbbox((0, 0), ch, font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    d.text(((S - w) / 2 - box[0], (S - h) / 2 - box[1]), ch, font=font, fill=hx(st["glyph"]))
    return img


def main():
    entries = []
    for th in THEMES:
        out = os.path.join(ROOT, "assets", "icons", th["id"])
        os.makedirs(out, exist_ok=True)
        for slot, label, glyph in SLOTS:
            render_icon(th, glyph).save(os.path.join(out, slot + ".png"), optimize=True)
            entries.append((th["id"], slot))
    lines = ["// AUTO-GENERATED by tools/gen/icons.py — do not edit by hand.",
             "// Glyphs: Ionicons (MIT). Artwork composed for Aura Themes.",
             "export const ICON_SLOTS = " + json.dumps([{"id": s, "label": l} for s, l, _ in SLOTS], indent=2) + " as const;",
             "", "export const ICON_IMAGES: Record<string, Record<string, number>> = {"]
    for th in THEMES:
        lines.append(f"  '{th['id']}': {{")
        for slot, _, _ in SLOTS:
            lines.append(f"    {slot}: require('../../assets/icons/{th['id']}/{slot}.png'),")
        lines.append("  },")
    lines += ["};", ""]
    with open(os.path.join(ROOT, "src/data/icons.generated.ts"), "w") as f:
        f.write("\n".join(lines))
    print("icons:", len(entries))


if __name__ == "__main__":
    main()
