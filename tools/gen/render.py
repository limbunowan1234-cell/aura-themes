"""Render the wallpaper catalog.

Usage:
  python3 tools/gen/render.py            # render everything
  python3 tools/gen/render.py id1 id2    # render specific wallpapers (preview)
Outputs:
  assets/wallpapers/full/<id>.jpg   1179x2556
  assets/wallpapers/thumb/<id>.jpg  390x845
  src/data/wallpapers.generated.ts  metadata + static require() map
"""
import hashlib
import json
import os
import sys
import datetime as dt
from multiprocessing import Pool

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from core import finish, W, H  # noqa: E402
from catalog import SPECS  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FULL = os.path.join(ROOT, "assets", "wallpapers", "full")
THUMB = os.path.join(ROOT, "assets", "wallpapers", "thumb")
META_DIR = os.path.join(ROOT, "tools", "gen", "out")
TW, TH = 390, 845


def seed_for(s):
    return int(hashlib.sha256(s.encode()).hexdigest()[:8], 16)


def analyse(im):
    small = im.resize((60, 130))
    arr = np.asarray(small, dtype=np.float32) / 255
    lum = 0.2126 * arr[..., 0] + 0.7152 * arr[..., 1] + 0.0722 * arr[..., 2]
    q = small.quantize(6, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()
    counts = sorted(q.getcolors(), reverse=True)
    idx = counts[0][1]
    dom = "#%02x%02x%02x" % tuple(pal[idx * 3: idx * 3 + 3])
    palette = []
    for _, i in counts[:5]:
        palette.append("#%02x%02x%02x" % tuple(pal[i * 3: i * 3 + 3]))
    # lock-screen clock region: rows 8%..28% of the screen
    clock = lum[int(130 * 0.08): int(130 * 0.28)]
    return dict(
        dominantColor=dom,
        palette=palette,
        tone="dark" if float(lum.mean()) < 0.45 else "light",
        clockFriendly=bool(float(clock.std()) < 0.09),
    )


def render(spec):
    rng = np.random.default_rng(seed_for(spec["id"]))
    img = spec["fn"](rng, **spec["params"])
    pil = finish(img, rng)
    os.makedirs(FULL, exist_ok=True)
    os.makedirs(THUMB, exist_ok=True)
    pil.save(os.path.join(FULL, spec["id"] + ".jpg"), "JPEG", quality=86, optimize=True, progressive=True, subsampling=0)
    pil.resize((TW, TH), Image.LANCZOS).save(os.path.join(THUMB, spec["id"] + ".jpg"), "JPEG", quality=80, optimize=True)
    meta = analyse(pil)
    h = seed_for(spec["id"] + "meta")
    created = dt.date(2026, 10, 20) - dt.timedelta(days=h % 75)
    meta.update(
        id=spec["id"], title=spec["title"], category=spec["category"], tags=spec["tags"],
        width=W, height=H, createdAt=created.isoformat(), popularity=40 + h % 60,
    )
    os.makedirs(META_DIR, exist_ok=True)
    with open(os.path.join(META_DIR, spec["id"] + ".json"), "w") as f:
        json.dump(meta, f)
    return spec["id"]


def write_ts():
    metas = []
    for spec in SPECS:
        with open(os.path.join(META_DIR, spec["id"] + ".json")) as f:
            metas.append(json.load(f))
    lines = [
        "// AUTO-GENERATED by tools/gen/render.py — do not edit by hand.",
        "// All images are original procedural artwork created for Aura Themes.",
        "import type { WallpaperMeta } from './types';",
        "",
        "export const WALLPAPER_META: WallpaperMeta[] = " + json.dumps(metas, indent=2) + ";",
        "",
        "export const WALLPAPER_FULL: Record<string, number> = {",
    ]
    for m in metas:
        lines.append(f"  '{m['id']}': require('../../assets/wallpapers/full/{m['id']}.jpg'),")
    lines += ["};", "", "export const WALLPAPER_THUMB: Record<string, number> = {"]
    for m in metas:
        lines.append(f"  '{m['id']}': require('../../assets/wallpapers/thumb/{m['id']}.jpg'),")
    lines += ["};", ""]
    out = os.path.join(ROOT, "src", "data", "wallpapers.generated.ts")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", out, len(metas), "wallpapers")


if __name__ == "__main__":
    ids = set(sys.argv[1:])
    specs = [s for s in SPECS if not ids or s["id"] in ids]
    ids_seen = [s["id"] for s in SPECS]
    assert len(ids_seen) == len(set(ids_seen)), "duplicate ids"
    with Pool(max(1, (os.cpu_count() or 2) - 1)) as pool:
        for done in pool.imap_unordered(render, specs):
            print("ok", done, flush=True)
    if not ids:
        write_ts()
